# Анализатор последовательностей ДНК

def main():
    # 1. Ввод данных
    s1 = input("Введите первую цепочку (например, ATCG): ").upper().strip()
    s2 = input("Введите вторую цепочку для проверки (необязательно): ").upper().strip()

    # Правила замены букв
    pairs = {'A': 'T', 'T': 'A', 'C': 'G', 'G': 'C'}

    # 2. Подсчет букв
    print("\n--- 1. ПОДСЧЕТ БУКВ ---")
    print(f"Длина цепочки: {len(s1)}")
    for letter in "ATCG":
        print(f"Букв {letter}: {s1.count(letter)}")

    # 3. Комплементарная и перевернутая (антипараллельная) цепочки
    comp = "".join([pairs.get(char, '?') for char in s1])
    anti = comp[::-1]  # переворачиваем строку

    print("\n--- 2. РЕЗУЛЬТАТ ---")
    print(f"Исходная:         {s1}")
    print(f"Комплементарная:  {comp}")
    print(f"Антипараллельная: {anti}")

    # 4. Поиск ошибок (сравнение двух цепочек)
    if s2:
        print("\n--- 3. ПРОВЕРКА ОШИБОК ---")
        if len(s1) != len(s2):
            print("Ошибка: цепочки разной длины!")
        else:
            errors = 0
            for i in range(len(s1)):
                # Проверяем, совпадает ли буква из s2 с парной буквой для s1
                if pairs.get(s1[i]) != s2[i]:
                    print(f"Ошибка в позиции {i + 1}: вместо '{pairs.get(s1[i])}' стоит '{s2[i]}'")
                    errors += 1
            
            if errors == 0:
                print("Ошибок нет, цепочки идеально подходят!")
            else:
                print(f"Всего ошибок: {errors}")

if __name__ == "__main__":
    main()
